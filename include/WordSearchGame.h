static inline void drawLetter5x5(int16_t x, int16_t y, char c, uint8_t color) {
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c < 'A' || c > 'Z') return;
    uint8_t idx = c - 'A';
    for (int8_t r = 0; r < 5; r++) {
        uint8_t row = pgm_read_byte(&font5x5[idx][r]);
        for (int8_t b = 0; b < 5; b++) {
            if (row & (1 << (4 - b))) {
                arduboy.drawPixel(x + b, y + r, color);
            }
        }
    }
}

